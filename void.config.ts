// The Worker, declared for Void (https://void.cloud): bindings, assets and
// defaults in one typed file. `voidPlugin()` reads it (edits need a dev
// server restart) and the build emits `dist/ssr/wrangler.json`, from which
// `vite.config.ts` (`emitCelldConfig`) derives the deploy-root
// `dist/wrangler.json` that celld-based platforms deploy.
import { defineConfig } from "void/config";

export default defineConfig({
  // Document head for every page. Void's document shell adds none of these
  // itself: `charset` and `viewport` must stay first, or phones render the
  // page as a zoomed-out 980px desktop layout. The rest add the PWA manifest (generated by vite-plugin-pwa from `manifest` +
  // `pwaAssets` in vite.config.ts — the plugin owns its content and icons),
  // theme color, and link previews. Void renders this head on the server:
  // with no index.html the plugin cannot inject these links itself.
  head: {
    title: "Void Debug",
    htmlAttrs: { lang: "en" },
    meta: [
      { charset: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { name: "description", content: "Backend compatibility probe for Void platforms." },
      { name: "theme-color", content: "#ffffff" },
      { name: "mobile-web-app-capable", content: "yes" },
      { name: "apple-mobile-web-app-capable", content: "yes" },
      { name: "apple-mobile-web-app-title", content: "Void Debug" },
      { property: "og:title", content: "Void Debug" },
      {
        property: "og:description",
        content: "Backend compatibility probe for Void platforms.",
      },
      { property: "og:type", content: "website" },
    ],
    link: [
      { rel: "manifest", href: "/manifest.webmanifest" },
      { rel: "icon", href: "/favicon.svg", type: "image/svg+xml" },
      { rel: "apple-touch-icon", href: "/apple-touch-icon-180x180.png" },
    ],
  },
  // Email/password auth (Better Auth). Noite and Outer both provision
  // BETTER_AUTH_SECRET at deploy when the app has none; a value set as an
  // app secret always wins.
  auth: { providers: ["email"] },
  // Managed sandbox (Void's `getSandbox()`): the default image is qualified
  // for celld platforms (no RUN, shim-carrying bases), so no custom
  // Dockerfile or platform image is needed.
  sandbox: true,
  cloudflare: {
    // The Worker name celld serves the app as.
    name: "void-debug",
    // The app's D1 database, provisioned by the platform on first deploy.
    // Read it in server modules with `env.DB` from `cloudflare:workers`.
    // `migrations_dir` is the repo folder `void db generate` writes;
    // platforms apply the committed files on deploy before the new code
    // goes live — including 0002_debug.sql, so a green deploy already
    // proves migrations work.
    d1_databases: [{ binding: "DB", database_name: "debug-db", migrations_dir: "db/migrations" }],
    // One bucket (the per-platform cap): the name is a prefix inside the
    // fleet's own bucket on Void platforms, so any stable name works.
    // Declared explicitly because binding inference only scans
    // conventional dirs — the R2 calls live in lib/ and would be missed.
    r2_buckets: [{ binding: "STORAGE", bucket_name: "debug-storage" }],
  },
  worker: {
    compatibility_date: "2026-09-01",
  },
});
